'use strict';
const assert = require('assert');
const crypto = require('crypto');
const ethers = require('../vendor/ethers.umd.min.js');
const Config = require('../farm-config');
const QuoteProtocol = require('../farm-exchange-protocol');
const DepositProtocol = require('../farm-live-deposit-protocol');
const { createLiveDepositService, SupabaseLiveDepositRepository } = require('../farm-live-deposit');
(async () => {
  const wallet=ethers.Wallet.createRandom(), address=wallet.address.toLowerCase(), quoteId=crypto.randomUUID(), eventId=crypto.randomUUID();
  const tx=`0x${'11'.repeat(32)}`, blockHash=`0x${'22'.repeat(32)}`, now=1700000000000;
  const quote={quoteId,wallet:address,direction:'deposit',coins:'100',amountUnits:'50000000',rateUnits:'50000000',rateVersion:2,issuedAt:now-1000,expiresAt:now+300000};
  const calls=[]; let latest=227, logAmount='50000000';
  const repo=new SupabaseLiveDepositRepository({ async request(method,path,body) {
    calls.push({method,path,body});
    if(path.endsWith('create_deposit_quote')) return quote;
    if(path.endsWith('get_deposit_quote')) return quote;
    if(path.endsWith('record_deposit')) return {status:'credited'};
    throw Error('unexpected');
  } });
  const provider={ getNetwork:async()=>({chainId:137n}), getTransactionReceipt:async()=>({hash:tx,blockNumber:100,blockHash,status:1,logs:[{index:7,address:Config.FTA_CONTRACT,topics:[ethers.id('Transfer(address,address,uint256)'),ethers.zeroPadValue(address,32),ethers.zeroPadValue(Config.TREASURY_ADDRESS,32)],data:ethers.toBeHex(BigInt(logAmount),32)}]}), getBlock:async()=>({number:100,hash:blockHash,timestamp:1700000000}),getBlockNumber:async()=>latest };
  const service=createLiveDepositService(repo,provider,{now:()=>now});
  const request={wallet:address,quoteId,coins:100,timestamp:now}; request.signature=await wallet.signMessage(DepositProtocol.quoteRequest(request));
  assert.deepStrictEqual(await service.issue(request),quote);
  await assert.rejects(service.issue({...request,coins:200}),e=>e.code==='LIVE_DEPOSIT_AUTH');
  await assert.rejects(service.issue({...request,timestamp:now-600001}),e=>e.code==='LIVE_DEPOSIT_AUTH');
  const submission={wallet:address,quoteId,eventId,txHash:tx,logIndex:7,quoteSignature:await wallet.signMessage(QuoteProtocol.message(quote))};
  submission.submissionSignature=await wallet.signMessage(DepositProtocol.submitRequest(submission));
  assert.strictEqual((await service.submit(submission)).status,'credited');
  const record=calls.find(c=>c.path.endsWith('record_deposit'));
  assert.deepStrictEqual(record.body,{p_quote_id:quoteId,p_event_id:eventId,p_wallet:address,p_tx_hash:tx,p_log_index:7,p_block_number:100,p_block_hash:blockHash,p_block_time_ms:now});
  await assert.rejects(service.submit({...submission,eventId:crypto.randomUUID()}),e=>e.code==='LIVE_DEPOSIT_AUTH');
  await assert.rejects(service.submit({...submission,txHash:`0x${'33'.repeat(32)}`}),e=>e.code==='LIVE_DEPOSIT_AUTH');
  await assert.rejects(service.submit({...submission,quoteSignature:'bad'}),e=>e.code==='LIVE_DEPOSIT_AUTH');
  latest=226; assert.strictEqual((await service.submit(submission)).status,'pending');
  latest=227; logAmount='1'; await assert.rejects(service.submit(submission),e=>e.code==='RECEIPT_MISMATCH');
  assert.strictEqual(calls.filter(c=>c.path.endsWith('record_deposit')).length,1);
  console.log('Dépôt réel préparé : demandes et transaction signées, preuve vérifiée avant crédit SQL');
})().catch(e=>{console.error(e);process.exitCode=1;});
