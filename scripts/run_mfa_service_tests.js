#!/usr/bin/env node
'use strict';
const assert = require('assert');
const crypto = require('crypto');
const { MfaService } = require('../mfa/service');
const { MemoryMfaRepository } = require('../mfa/memory-repository');
const { hotp } = require('../mfa/totp');
const user = '7b0f7399-ca7a-4b6f-a4f1-9f4266f0f21c';
const other = '7b0f7399-ca7a-4b6f-a4f1-9f4266f0f21d';
(async () => {
  let now = 1800000000000;
  const repository = new MemoryMfaRepository();
  const service = new MfaService({ repository, key: crypto.randomBytes(32), now: () => now });
  assert.deepStrictEqual(await service.status(user), { enabled: false });
  const enrollment = await service.beginEnrollment(user);
  assert.deepStrictEqual(await service.status(user), { enabled: false });
  assert.ok(!JSON.stringify(repository.records.get(user)).includes(enrollment.secret));
  await assert.rejects(service.confirmEnrollment(user, 'wrong'), (e) => e.code === 'MFA_INVALID');
  const { recoveryCodes } = await service.confirmEnrollment(user, hotp(enrollment.secret, Math.floor(now / 30000)));
  assert.strictEqual(recoveryCodes.length, 10);
  assert.deepStrictEqual(await service.status(user), { enabled: true });
  await assert.rejects(service.beginEnrollment(user), (e) => e.code === 'MFA_ALREADY_ENABLED');
  await assert.rejects(service.consumeCode(user, hotp(enrollment.secret, Math.floor(now / 30000))), (e) => e.code === 'MFA_INVALID');
  now += 30000;
  const results = await Promise.allSettled([service.consumeCode(user, hotp(enrollment.secret, Math.floor(now / 30000))), service.consumeCode(user, hotp(enrollment.secret, Math.floor(now / 30000)))]);
  assert.strictEqual(results.filter((x) => x.status === 'fulfilled').length, 1);
  const recovery = await Promise.allSettled([service.consumeCode(user, recoveryCodes[0]), service.consumeCode(user, recoveryCodes[0])]);
  assert.strictEqual(recovery.filter((x) => x.status === 'fulfilled').length, 1);
  assert.ok(!JSON.stringify(repository.records.get(user)).includes(recoveryCodes[1]));
  await assert.rejects(service.consumeCode(other, recoveryCodes[1]), (e) => e.code === 'MFA_NOT_ENABLED');
  for (let i = 0; i < 4; i++) await assert.rejects(service.consumeCode(user, 'wrong'));
  await assert.rejects(service.consumeCode(user, recoveryCodes[1]), (e) => e.code === 'MFA_LOCKED');
  now += 15 * 60 * 1000;
  assert.strictEqual((await service.consumeCode(user, recoveryCodes[1])).method, 'recovery');
  await assert.rejects(service.disable(user, 'wrong'), (e) => e.code === 'MFA_INVALID');
  assert.deepStrictEqual(await service.status(user), { enabled: true });
  await service.disable(user, recoveryCodes[2]);
  assert.deepStrictEqual(await service.status(user), { enabled: false });
  await assert.rejects(service.consumeCode(user, recoveryCodes[3]), (e) => e.code === 'MFA_NOT_ENABLED');
  const pending = await service.beginEnrollment(other);
  now += 10 * 60 * 1000;
  await assert.rejects(service.confirmEnrollment(other, hotp(pending.secret, Math.floor(now / 30000))), (e) => e.code === 'MFA_ENROLLMENT_EXPIRED');
  console.log('MFA domain tests passed: enrollment, replay, recovery, lockout and concurrent consumption.');
})().catch((error) => { console.error(error); process.exitCode = 1; });
